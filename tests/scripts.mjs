  await expect(noteReader).toBeVisible();
  await noteReader.getByRole("button", { name: "Zur Übersicht", exact: true }).click();
  await expect(noteReader).toHaveCount(0);
  assert.ok(page.url().endsWith("#script=" + script.id));

