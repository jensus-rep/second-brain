  await expect(reader.locator(".script-outline-content")).toBeVisible();
  await reader.locator(".script-outline ol button").nth(1).click();
  await expect(reader.locator(".script-chapter-title")).toHaveText("Die Methode begründen");
  await expect(reader.locator(".script-outline-content")).not.toBeVisible();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.equal(await reader.locator(".script-scroll").evaluate(element => element.scrollWidth > element.clientWidth), false);
  await page.screenshot({ path: ".sites-runtime/qa/scripts-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await visibleButton("Import & Datensicherung").click();
  const jsonDownload = page.waitForEvent("download");
  await visibleButton("Nur Wissensdaten als JSON").click();
  const json = await jsonDownload; const jsonPath = ".sites-runtime/qa/scripts-backup.json"; await json.saveAs(jsonPath);
  const backup = JSON.parse(await readFile(jsonPath, "utf8"));
  assert.deepEqual(backup.scripts, (await snapshot()).workspace.scripts);
  const zipDownload = page.waitForEvent("download");
  await visibleButton("Sicherung herunterladen").click();
  const zip = await zipDownload; const zipPath = ".sites-runtime/qa/scripts-backup.zip"; await zip.saveAs(zipPath);
  const files = unzipSync(new Uint8Array(await readFile(zipPath)));
  assert.deepEqual(JSON.parse(strFromU8(files["workspace.json"])).scripts, backup.scripts);
