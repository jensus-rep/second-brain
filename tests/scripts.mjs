  assert.equal(legacyResponse.status(), 400);
  assert.ok((await legacyResponse.json()).error.includes("Skripte"));
  const changedNote = { ...note, content: note.content + "\nEine neue Einordnung.", updatedAt: new Date().toISOString() };
  await write({ ...current.workspace, notes: current.workspace.notes.map(item => item.id === note.id ? changedNote : item) });
  const conflict = await page.request.put(api, { data: { revision: current.revision, workspace: current.workspace } });
  assert.equal(conflict.status(), 409);
  await page.reload({ waitUntil: "networkidle" });
  await expect(reader.getByRole("status")).toContainText("Quellenstand prüfen");
  await reader.getByRole("button", { name: "Nach Prüfung als aktuell markieren", exact: true }).click();
  await saved(w => w.scripts.find(s => s.id === script.id).chapters[0].sources[0].fingerprint === scriptSourceFingerprint(changedNote));
  await expect(reader.getByRole("status")).toHaveCount(0);
  await reader.getByRole("button", { name: note.title, exact: true }).click();
