  await expect(reader).toBeVisible();

  await mkdir(".sites-runtime/qa", { recursive: true });
  const mdDownload = page.waitForEvent("download");
  await reader.getByRole("button", { name: "Markdown exportieren", exact: true }).click();
  const md = await mdDownload; await md.saveAs(".sites-runtime/qa/script-export.md");
  assert.ok((await readFile(".sites-runtime/qa/script-export.md", "utf8")).includes("SkriptSuchwort"));
  await page.screenshot({ path: ".sites-runtime/qa/scripts-desktop.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(reader).toBeVisible();
  await expect(reader.locator(".script-outline-content")).not.toBeVisible();
